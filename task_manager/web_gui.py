@app.route('/api/tasks', methods=['GET'])
def get_tasks():
    priority_filter = request.args.get('priority', 'all')
    status_filter = request.args.get('status', 'all')
    search_query = request.args.get('search', '')
    
    tasks = storage.get_all_tasks()
    
    # Apply filters
    if priority_filter != 'all':
        tasks = [t for t in tasks if t.priority.value == priority_filter]
    
    if status_filter == 'completed':
        tasks = [t for t in tasks if t.completed]
    elif status_filter == 'pending':
        tasks = [t for t in tasks if not t.completed]
    elif status_filter == 'overdue':
        now = datetime.now()
        tasks = [t for t in tasks if not t.completed and t.due_date and t.due_date < now]
    
    if search_query:
        tasks = [t for t in tasks if search_query.lower() in t.title.lower() or search_query.lower() in (t.description or '').lower()]
    
    # Calculate stats
    stats = {
        'total': len(storage.get_all_tasks()),
        'completed': len([t for t in storage.get_all_tasks() if t.completed]),
        'pending': len([t for t in storage.get_all_tasks() if not t.completed]),
        'overdue': len([t for t in storage.get_all_tasks() if not t.completed and t.due_date and t.due_date < datetime.now()])
    }
    
    return jsonify({
        'tasks': [task_to_dict(t) for t in tasks],
        'stats': stats
    })

