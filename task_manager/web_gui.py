def create_task():
    data = request.json
    
    task = Task(
        title=data['title'],
        description=data.get('description'),
        priority=Priority(data.get('priority', 'medium')),
        due_date=datetime.fromisoformat(data['due_date']) if data.get('due_date') else None,
        repeat_frequency=RepeatFrequency(data['repeat_frequency']) if data.get('repeat_frequency') else None,
        reminder_enabled=data.get('reminder_enabled', False)
    )
    
    # Add tags
    for tag_name in data.get('tags', []):
        task.add_tag(Tag(name=tag_name))
    
    # Add subtasks
    for subtask_title in data.get('subtasks', []):
        task.add_subtask(SubTask(title=subtask_title))
    
    storage.add_task(task)
    return jsonify(task_to_dict(task)), 201

@app.route('/api/tasks/<int:task_id>', methods=['PUT'])
def update_task(task_id):
    task = storage.get_task(task_id)
    if not task:
        return jsonify({'error': 'Task not found'}), 404
    
    data = request.json
    task.title = data.get('title', task.title)
    task.description = data.get('description', task.description)
    task.priority = Priority(data.get('priority', task.priority.value))
    task.due_date = datetime.fromisoformat(data['due_date']) if data.get('due_date') else None
    task.repeat_frequency = RepeatFrequency(data['repeat_frequency']) if data.get('repeat_frequency') else None
    task.reminder_enabled = data.get('reminder_enabled', task.reminder_enabled)
    
    # Update tags
    task.tags = []
    for tag_name in data.get('tags', []):
        task.add_tag(Tag(name=tag_name))
    
    # Update subtasks
    task.subtasks = []
    for subtask_title in data.get('subtasks', []):
        task.add_subtask(SubTask(title=subtask_title))
    
    storage.save()
    return jsonify(task_to_dict(task))

