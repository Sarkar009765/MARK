def task_to_dict(task):
    # Get tag objects from storage if tags are stored as IDs
    from storage import TaskStorage
    storage = TaskStorage()
    
    tag_objects = []
    for tag_id in task.tags:
        tag_obj = storage.get_tag(tag_id)
        if tag_obj:
            tag_objects.append(tag_obj)
    
    return {
        'id': task.id,
        'title': task.title,
        'description': task.description,
        'priority': task.priority.value,
        'completed': task.completed,
        'completed_at': task.completed_at.isoformat() if task.completed_at else None,
        'created_at': task.created_at.isoformat(),
        'due_date': task.due_date.isoformat() if task.due_date else None,
        'repeat_frequency': task.repeat_frequency.value if task.repeat_frequency else None,
        'reminder_enabled': task.reminder_enabled,
        'tags': [{'id': t.id, 'name': t.name} for t in tag_objects],
        'subtasks': [{
            'id': s.id,
            'title': s.title,
            'completed': s.completed
        } for s in task.sub_tasks]
    }

