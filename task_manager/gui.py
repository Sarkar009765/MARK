class ManageTagsDialog:
    """Dialog for managing tags."""
    
    def __init__(self, parent, storage: TaskStorage):
        self.refresh_needed = False
        
        self.dialog = tk.Toplevel(parent)
        self.dialog.title("Manage Tags")
        self.dialog.geometry("400x400")
        self.dialog.transient(parent)
        self.dialog.grab_set()
        
        self.storage = storage
        
        main_frame = ttk.Frame(self.dialog, padding=20)
        main_frame.pack(fill=tk.BOTH, expand=True)
        
        # Tag list
        ttk.Label(main_frame, text="Existing Tags:").pack(anchor=tk.W)
        
        self.tag_listbox = tk.Listbox(main_frame, height=10)
        self.tag_listbox.pack(fill=tk.BOTH, expand=True, pady=5)
        
        self._load_tags()
        
        # Buttons
        button_frame = ttk.Frame(main_frame)
        button_frame.pack(fill=tk.X, pady=10)
        
        ttk.Button(button_frame, text="Add", command=self._add_tag).pack(side=tk.LEFT, padx=2)
        ttk.Button(button_frame, text="Delete", command=self._delete_tag).pack(side=tk.LEFT, padx=2)
        ttk.Button(button_frame, text="Close", command=self.dialog.destroy).pack(side=tk.RIGHT, padx=2)
        
        self.dialog.wait_window()
    
    def _load_tags(self):
        """Load tags into listbox."""
        self.tag_listbox.delete(0, tk.END)
        tags = self.storage.get_all_tags()
        for tag in tags:
            self.tag_listbox.insert(tk.END, f"{tag.id}: {tag.name} ({tag.color})")
    
    def _add_tag(self):
        """Add a new tag."""
        name = simpledialog.askstring("Add Tag", "Enter tag name:")
        if not name:
            return
        
        color = colorchooser.askcolor(title="Choose tag color")[1] or "#FFFFFF"
        
        self.storage.add_tag(name, color)
        self._load_tags()
        self.refresh_needed = True
    
    def _delete_tag(self):
        """Delete selected tag."""
        selection = self.tag_listbox.curselection()
        if not selection:
            messagebox.showwarning("Warning", "Please select a tag")
            return
        
        tag_info = self.tag_listbox.get(selection[0])
        tag_id = int(tag_info.split(':')[0])
        
        if messagebox.askyesno("Confirm", "Delete this tag?"):
            self.storage.delete_tag(tag_id)
            self._load_tags()
            self.refresh_needed = True


