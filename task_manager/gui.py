    def _countdown(self, window):
        """Countdown timer for Pomodoro."""
        if self.pomodoro_running and self.pomodoro_time > 0:
            minutes = self.pomodoro_time // 60
            seconds = self.pomodoro_time % 60
            time_str = f"{minutes:02d}:{seconds:02d}"
            self.timer_label.config(text=time_str)
            self.pomodoro_time -= 1
            window.after(1000, lambda: self._countdown(window))
        elif self.pomodoro_time == 0:
            self.timer_label.config(text="00:00")
            messagebox.showinfo("Pomodoro Complete", "Time's up! Take a break.")
    
    def _complete_pomodoro(self, window):
        """Complete and log Pomodoro session."""
        self.storage.log_pomodoro_session(self.selected_task_id)
        window.destroy()
        task = self.storage.get_task(self.selected_task_id)
        self._display_task_details(task)
        self.status_label.config(text="Pomodoro session logged")
    
