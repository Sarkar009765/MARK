@cli.command()
def stats():
    """Show task statistics."""
    storage = TaskStorage()
    all_tasks = storage.get_all_tasks()
    
    total = len(all_tasks)
    completed = sum(1 for t in all_tasks if t.completed)
    pending = total - completed
    
    priority_counts = {}
    for task in all_tasks:
        priority_counts[task.priority.name] = priority_counts.get(task.priority.name, 0) + 1
    
    click.echo("\n=== Task Statistics ===\n")
    click.echo(f"Total Tasks:     {total}")
    click.echo(f"Completed:       {completed} ({completed/total*100:.1f}%)" if total > 0 else "Completed:       0")
    click.echo(f"Pending:         {pending}")
    click.echo("\nBy Priority:")
    for priority, count in sorted(priority_counts.items()):
        click.echo(f"  {priority:<10} {count}")
    click.echo()


