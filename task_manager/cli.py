@click.group()
def cli():
    """Task Manager - Manage your tasks efficiently."""
    pass


@cli.command()
@click.argument('title')
@click.option('--description', '-d', default='', help='Description of the task')
@click.option('--priority', '-p', type=click.Choice(['LOW', 'MEDIUM', 'HIGH', 'CRITICAL']), 
              default='MEDIUM', help='Priority level')
@click.option('--due-date', '-D', type=click.DateTime(formats=['%Y-%m-%d']), 
              help='Due date (YYYY-MM-DD)')
def add(title, description, priority, due_date):
    """Add a new task."""
    storage = TaskStorage()
    
    task = Task(
        id=0,  # Will be set by database
        title=title,
        description=description,
        priority=Priority[priority],
        due_date=due_date
    )
    
    task_id = storage.add_task(task)
    click.echo(f"✓ Task added successfully with ID: {task_id}")


@cli.command()
@click.option('--all', 'show_all', is_flag=True, help='Show all tasks including completed')
def list(show_all):
    """List all tasks."""
    storage = TaskStorage()
    
    if show_all:
        tasks = storage.get_all_tasks()
    else:
        tasks = storage.get_pending_tasks()
    
    if not tasks:
        click.echo("No tasks found.")
        return
    
    click.echo(f"\n{'ID':<5} {'Status':<8} {'Priority':<10} {'Title':<30} {'Due Date':<12}")
    click.echo("-" * 75)
    
    for task in tasks:
        status = "✓ Done" if task.completed else "○ Pending"
        priority_str = task.priority.name
        due_date_str = task.due_date.strftime('%Y-%m-%d') if task.due_date else "-"
        title_display = task.title[:27] + "..." if len(task.title) > 30 else task.title
        
        click.echo(f"{task.id:<5} {status:<8} {priority_str:<10} {title_display:<30} {due_date_str:<12}")
    
    click.echo(f"\nTotal: {len(tasks)} task(s)")


@cli.command()
@click.argument('task_id', type=int)
def complete(task_id):
    """Mark a task as complete."""
    storage = TaskStorage()
    task = storage.get_task(task_id)
    
    if not task:
        click.echo(f"✗ Task with ID {task_id} not found.")
        return
    
    task.mark_complete()
    storage.update_task(task)
    click.echo(f"✓ Task '{task.title}' marked as complete.")


@cli.command()
@click.argument('task_id', type=int)
@click.confirmation_option(prompt='Are you sure you want to delete this task?')
def delete(task_id):
    """Delete a task."""
    storage = TaskStorage()
    task = storage.get_task(task_id)
    
